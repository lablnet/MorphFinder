function classifyDotEntry(name: string): { category: 'Developer' | 'AI' | 'System'; description: string } {
  const nameLower = name.toLowerCase();
  if (
    nameLower.includes('ollama') ||
    nameLower.includes('lmstudio') ||
    nameLower.includes('gemini') ||
    nameLower.includes('codex') ||
    nameLower.includes('grok') ||
    nameLower.includes('claude')
  ) {
    return {
      category: 'AI',
      description: `Local AI models and configurations for ${name}. Cleaning this folder may delete downloaded model files.`,
    };
  }
  if (nameLower === '.cache' || nameLower === '.local' || nameLower === '.zsh_sessions' || nameLower === '.trash') {
    return {
      category: 'System',
      description: `System cache or shell sessions directory ${name}. Safe to delete, but some settings will be regenerated.`,
    };
  }
  return {
    category: 'Developer',
    description: `Developer tools and environment configurations for ${name}. Note: Cleaning this folder resets settings, libraries, or extensions for this tool.`,
  };
}

export async function scanCaches(): Promise<CacheScanResult> {
  // Only support macOS for cache scanning
  if (process.platform !== 'darwin') {
    return { isSupported: false, targets: [] };
  }

  const targets: CacheTarget[] = [];
  const scannedPaths = new Set<string>();

  // 1. Scan static predefined targets
  for (const spec of STATIC_TARGET_SPECS) {
    const fullPath = expandPath(spec.path);
    scannedPaths.add(fullPath);

    if (await pathExists(fullPath)) {
      const size = await calculateDirSize(fullPath);
      if (size > 0) {
        targets.push({
          id: spec.id,
          name: spec.name,
          category: spec.category,
          path: fullPath,
          sizeInBytes: size,
          description: spec.description,
        });
      }
    }
  }

  // Helper to scan dynamic directories and classify them
  async function scanDirectoryDynamic(parentDir: string, category: 'Application' | 'System'): Promise<void> {
    const parentPath = expandPath(parentDir);
    if (!(await pathExists(parentPath))) return;

    try {
      const entries = await readdir(parentPath, { withFileTypes: true });
      // Calculate sizes in parallel
      await Promise.all(
        entries.map(async (entry) => {
          if (!entry.isDirectory()) return;

          const dirPath = join(parentPath, entry.name);
          // Skip if already processed in static targets
          if (scannedPaths.has(dirPath)) return;

          const size = await calculateDirSize(dirPath);
          const threshold = 50 * 1024 * 1024; // Only show directories taking > 50MB

          if (size > threshold) {
            const appName = entry.name;
            const description = category === 'Application'
              ? `Application support data and local databases for ${appName}. Note: Clearing this folder completely resets app configurations.`
              : `Cached temporary files for ${appName}. Safe to clear; files will be regenerated as needed.`;

            targets.push({
              id: `dynamic-${category.toLowerCase()}-${appName}`,
              name: `${appName} ${category === 'Application' ? 'App Data' : 'Caches'}`,
              category: category === 'Application' ? 'Application' : 'System',
              path: dirPath,
              sizeInBytes: size,
              description,
            });
          }
        })
      );
    } catch {
      // Ignore reading errors of parent directories
    }
  }

  // 2. Scan ~/Library/Application Support
  await scanDirectoryDynamic('~/Library/Application Support', 'Application');

  // 3. Scan ~/Library/Caches
  await scanDirectoryDynamic('~/Library/Caches', 'System');

  // 4. Scan dotfiles/dotfolders in home directory (excluding predefined static targets)
  const homePath = homedir();
  try {
    const homeEntries = await readdir(homePath, { withFileTypes: true });
    await Promise.all(
      homeEntries.map(async (entry) => {
        // Only process entries starting with . (excluding . and ..)
        if (!entry.name.startsWith('.') || entry.name === '.' || entry.name === '..') return;

        const entryPath = join(homePath, entry.name);
        if (scannedPaths.has(entryPath)) return;

        try {
          const stats = await lstat(entryPath);
          let size = 0;
          if (stats.isDirectory()) {
            size = await calculateDirSize(entryPath);
          } else if (stats.isFile()) {
            size = stats.blocks !== undefined ? stats.blocks * 512 : stats.size;
          }

          const threshold = 3 * 1024 * 1024; // Show dot files/folders taking > 3MB
          if (size > threshold) {
            const { category, description } = classifyDotEntry(entry.name);
            targets.push({
              id: `dynamic-dot-${entry.name}`,
              name: entry.name,
              category,
              path: entryPath,
              sizeInBytes: size,
              description,
            });
          }
        } catch {
          // Ignore individual stat/scan errors
        }
      })
    );
  } catch {
    // Ignore home readdir errors
  }

  // Sort targets by size descending
  targets.sort((a, b) => b.sizeInBytes - a.sizeInBytes);

  return { isSupported: true, targets };
}

export async function cleanCaches(targetIds: string[]): Promise<CacheCleanResult> {
  const cleanedSizes: Record<string, number> = {};
  const errors: Record<string, string> = {};

  if (process.platform !== 'darwin') {
    return { success: false, cleanedSizes, errors };
  }

  // Get current state to know sizes before deletion
  const { targets } = await scanCaches();

  for (const targetId of targetIds) {
    const target = targets.find((t) => t.id === targetId);
    if (!target) {
      errors[targetId] = 'Target not found or no longer exists.';
      continue;
    }

    try {
      // Force remove recursively
      await rm(target.path, { recursive: true, force: true });
      cleanedSizes[targetId] = target.sizeInBytes;
    } catch (err) {
      errors[targetId] = err instanceof Error ? err.message : String(err);
    }
  }

  const success = Object.keys(errors).length === 0;
  return { success, cleanedSizes, errors };
}
