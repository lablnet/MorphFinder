import { readdir, lstat, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { homedir } from 'node:os';
import type { CacheTarget, CacheScanResult, CacheCleanResult } from '../../shared/types/cache';
import { pathExists } from './fileSystemService';

// Expand tilde in path to home directory
function expandPath(p: string): string {
  if (p.startsWith('~/')) {
    return join(homedir(), p.slice(2));
  }
  if (p === '~') {
    return homedir();
  }
  return p;
}

// Compute directory size recursively, with limited concurrency to be fast and safe
async function calculateDirSize(dirPath: string): Promise<number> {
  let size = 0;

  async function walk(currentPath: string): Promise<void> {
    try {
      const entries = await readdir(currentPath, { withFileTypes: true });
      // Process entries in batches of 30 to limit concurrency and avoid EMFILE
      const batchSize = 30;
      for (let i = 0; i < entries.length; i += batchSize) {
        const batch = entries.slice(i, i + batchSize);
        await Promise.all(
          batch.map(async (entry) => {
            const entryPath = join(currentPath, entry.name);
            try {
              // Use lstat to avoid following symbolic links
              const stats = await lstat(entryPath);
              if (stats.isDirectory()) {
                await walk(entryPath);
              } else if (stats.isFile()) {
                const physicalSize = stats.blocks !== undefined ? stats.blocks * 512 : stats.size;
                size += physicalSize;
              }
            } catch {
              // Ignore stat/read errors for single files (e.g. permission or broken symlinks)
            }
          })
        );
      }
    } catch {
      // Ignore readdir errors (e.g. permission denied)
    }
  }

  await walk(dirPath);
  return size;
}

